import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
async function files(dir) {
  try {
    const entries = await readdir(dir, { withFileTypes: true });
    return (
      await Promise.all(
        entries.map((e) =>
          e.isDirectory() ? files(`${dir}/${e.name}`) : [`${dir}/${e.name}`],
        ),
      )
    ).flat();
  } catch (e) {
    if (e.code === "ENOENT") return [];
    throw e;
  }
}
// Only stable, explicitly generated public resources belong in this cache.
// Next.js chunks/fonts already use content-addressed HTTP caching. Build caches
// can contain obsolete chunks that Vercel does not publish, so never enumerate them.
const common = await files("public/optimized");
const host = (await files("public/emulatorjs")).filter(
  (p) => !p.endsWith("manifest.json"),
);
const netplay = (await files("public/netplay-emulatorjs")).filter(
  (p) => !p.includes("/source/") && !p.endsWith("manifest.json"),
);
const assets = {};
for (const [group, paths] of [
  ["common", common],
  ["host", host],
  ["netplay", netplay],
]) {
  for (const path of paths.sort()) {
    const url = path.startsWith("public/")
      ? path.slice(6)
      : path.replace(".next/static/", "/_next/static/");
    assets[url] = {
      group,
      sha256: createHash("sha256")
        .update(await readFile(path))
        .digest("hex"),
    };
  }
}
const source = (await files("src"))
  .filter((p) => /\.(tsx?|css|woff2)$/.test(p))
  .concat([
    "public/emulator.html",
    "public/netplay-emulator.html",
    "scripts/service-worker.js",
    "package.json",
  ]);
const hash = createHash("sha256").update(JSON.stringify(assets));
for (const path of source.sort()) hash.update(await readFile(path));
const version = hash.digest("hex").slice(0, 16);
await writeFile(
  "public/client-assets.json",
  JSON.stringify({ version, assets }),
);
const worker = await readFile("scripts/service-worker.js", "utf8");
await writeFile(
  "public/sw.js",
  `// Generated by scripts/prepare-client.mjs\nconst VERSION = ${JSON.stringify(version)};\nconst ASSETS = ${JSON.stringify(assets)};\n${worker}`,
);
console.log(
  `Arquivos preparados: ${common.length} públicos, ${host.length} do emulador · ${version}`,
);
